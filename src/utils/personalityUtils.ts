export const TONAL_INSTRUCTIONS: Record<ZoyaTone, string> = {
  friendly: FRIENDLY_MODE,
  playful: PLAYFUL_MODE,
  sassy: SASSY_MODE,
  romantic: ROMANTIC_MODE,
  caring: CARING_MODE,
  // Backward-compatible aliases for any stored preference
  loving: ROMANTIC_MODE,
  professional: FRIENDLY_MODE,
  casual: FRIENDLY_MODE,
};

export function normalizeTone(
  tone?: string | null
): "friendly" | "playful" | "sassy" | "romantic" | "caring" {
  if (tone === "playful") return "playful";
  if (tone === "sassy") return "sassy";
  if (tone === "romantic" || tone === "loving") return "romantic";
  if (tone === "caring") return "caring";
  return "friendly";
}

export function getSystemInstruction(tone?: ZoyaTone | string): string {
  const normalized = normalizeTone(tone);
  return TONAL_INSTRUCTIONS[normalized];
}
